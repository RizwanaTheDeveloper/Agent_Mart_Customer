// Build the embedded document from editable feature source, preserving module order.
// assets/apk remains the unchanged reference used by the visual regression tests.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/features/apk/source-manifest.json'), 'utf8'));
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const sources = {
  'index.html': read(manifest.html),
  'styles.css': [manifest.css, ...(manifest.styles || [])].map(read).join('\n\n'),
  'locales.js': read(manifest.locales),
  'app.js': manifest.scripts.map(read).join('\n\n'),
};
// Catch invalid edits before publishing a broken embedded document.
const vm = require('node:vm');
new vm.Script(sources['locales.js'], { filename: manifest.locales });
new vm.Script(sources['app.js'], { filename: 'assembled-features.js' });
const output = path.join(root, 'src/features/apk/apkAssets.generated.ts');
fs.mkdirSync(path.dirname(output), { recursive: true });
const literal = value => '`' + value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
const generated = '// Generated by npm run build:apk-assets. Edit the files in source-manifest.json.\n' +
  'export const apkAssets = {\n' + Object.entries(sources).map(([name, value]) =>
    `  ${JSON.stringify(name)}: ${literal(value)},`).join('\n') + '\n} as const;\n';
fs.writeFileSync(output, generated);
console.log(`Prepared document from ${manifest.scripts.length} editable feature modules.`);
